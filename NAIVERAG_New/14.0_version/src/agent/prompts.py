def get_system_prompt(agent_type: str) -> str:
    """获取对应类型的系统提示词"""
    prompts = {
        "consultation": CONSULTATION_SYSTEM_PROMPT,
        "contract": CONTRACT_REVIEW_SYSTEM_PROMPT,
        "document": DOCUMENT_GENERATION_SYSTEM_PROMPT,
        "risk": RISK_ASSESSMENT_SYSTEM_PROMPT,
    }
    return prompts.get(agent_type, CONSULTATION_SYSTEM_PROMPT)


def get_procedure_guide(procedure_type: str) -> str:
    """获取流程指引"""
    return PROCEDURE_GUIDES.get(procedure_type, "暂未提供该流程指引，请咨询专业人士。")


def format_consultation_prompt(question: str, context: str = "") -> str:
    """构建咨询提示词"""
    context_part = f"\n\n## 参考信息\n{context}" if context else ""
    return f"""{CONSULTATION_SYSTEM_PROMPT}

## 用户问题
{question}
{context_part}

请用通俗易懂的语言回答用户的问题。
"""


def format_contract_review_prompt(contract_text: str, law_context: str = "") -> str:
    """构建合同审查提示词"""
    law_part = f"\n\n## 相关法律条文\n{law_context}" if law_context else ""
    return f"""{CONTRACT_REVIEW_SYSTEM_PROMPT}

## 合同内容
{contract_text}
{law_part}

请审查合同，识别风险条款并给出修改建议。
"""


def format_document_prompt(doctype: str, facts: str, legal_basis: str = "") -> str:
    """构建文书生成提示词"""
    law_part = f"\n\n## 相关法律条文\n{legal_basis}" if legal_basis else ""
    return f"""{DOCUMENT_GENERATION_SYSTEM_PROMPT}

## 文书类型
{doctype}

## 事实情况
{facts}
{law_part}

请生成完整的法律文书。
"""


def format_risk_assessment_prompt(case_type: str, facts: str, case_context: str = "") -> str:
    """构建风险评估提示词"""
    case_part = f"\n\n## 类似案例参考\n{case_context}" if case_context else ""
